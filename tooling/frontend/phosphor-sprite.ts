import { readFile, writeFile } from "node:fs/promises"
import { join } from "node:path"

import { typedKeys } from "../../framework/foundation/mod.ts"
import { isMain } from "../entrypoint.ts"

// Builds the static Phosphor SVG sprite served at /icons/phosphor.svg. Only glyphs referenced by
// the RITSEI icon registry are included, so the application never loads the full icon font.

type SelectionIcon = { icon: { paths: readonly string[] }; properties: { name: string } }

export const spritePath = "apps/web/public/icons/phosphor.svg"
const registryPath = "apps/web/src/ui/icons/registry.ts"

// Tooling may not import application UI modules, so the registry's glyph names are read as text.
// tests/frontend/iconography.test.ts checks the result against the imported registry.
export const readRegistryGlyphs = async (): Promise<readonly string[]> => {
  const source = (await readFile(registryPath, "utf8")).replaceAll("\r\n", "\n")

  const glyphs = [...source.matchAll(/^\s*"[a-z0-9.-]+": "([a-z0-9-]+)",?$/gm)].map(
    ([, glyph]) => glyph!,
  )

  if (glyphs.length === 0) throw new Error(`no icon glyphs found in ${registryPath}`)

  return [...new Set(glyphs)].toSorted()
}

const variants = { regular: "", fill: "-fill" } as const

export const spriteSymbolId = (glyph: string, variant: keyof typeof variants) =>
  `ph-${glyph}${variants[variant]}`

const loadSelection = async (variant: keyof typeof variants) => {
  // The package's export map hides its source assets, so read them from the web app's install.
  const root = join(process.cwd(), "apps/web/node_modules/@phosphor-icons/web")

  // SAFETY: selection.json has the shape published by the installed @phosphor-icons/web package.
  const selection = JSON.parse(
    await readFile(join(root, "src", variant, "selection.json"), "utf8"),
  ) as { icons: readonly SelectionIcon[] }

  return new Map(
    selection.icons.map((icon) => [icon.properties.name.split(",")[0]!.trim(), icon] as const),
  )
}

export const buildSprite = async (): Promise<string> => {
  const glyphs = await readRegistryGlyphs()
  const symbols: string[] = []

  for (const variant of typedKeys(variants)) {
    const selection = await loadSelection(variant)

    for (const glyph of glyphs) {
      const icon = selection.get(`${glyph}${variants[variant]}`)

      if (icon === undefined) throw new Error(`Phosphor ${variant} glyph not found: ${glyph}`)
      // Paths use relative commands, so they are copied verbatim: rounding would accumulate drift.
      const d = icon.icon.paths.join("")
      symbols.push(
        `<symbol id="${spriteSymbolId(glyph, variant)}" viewBox="0 0 1024 1024"><path d="${d}"/></symbol>`,
      )
    }
  }

  return `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Generated by tooling/frontend/phosphor-sprite.ts from @phosphor-icons/web (MIT). -->\n${symbols.join("\n")}\n</svg>\n`
}

if (isMain(import.meta.url)) {
  await writeFile(spritePath, await buildSprite())
  console.log(`wrote ${spritePath}`)
}
