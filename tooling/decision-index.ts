// Generates the ADR index in docs/decisions/README.md from the ADR headers (ADR-0123), so the index
// cannot drift from the records it lists. Only the block between the index markers is generated.
import { readdir, readFile, stat } from "node:fs/promises"

export const decisionIndexTarget = "docs/decisions/README.md"
const decisionRoot = "docs/decisions"
const start = "<!-- adr-index:start (generated by `pnpm run ritsei gen`; do not edit) -->"
const end = "<!-- adr-index:end -->"

/** ADRs from this number on must name the owner documents they change (ADR-0123). */
const firstWithChanges = 123

export type DecisionRecord = {
  readonly id: string
  /** Path relative to docs/decisions. */
  readonly path: string
  readonly title: string
  readonly status: string
  readonly changes: string | undefined
}

const header = (text: string, key: string) =>
  text
    .match(new RegExp(`^- ${key}:[ \\t]*(.*(?:\\n {2,}\\S.*)*)`, "m"))?.[1]
    ?.replace(/\s+/g, " ")
    .trim()

export const parseDecision = (path: string, text: string): DecisionRecord => {
  const id = path.match(/(?:^|\/)(\d{4})-[^/]+\.md$/)?.[1]
  const heading = text.match(/^# ADR-(\d{4}):\s*(.+)$/m)
  const status = header(text, "Status")?.split(/[\s(]/)[0]

  if (id === undefined || heading === null || heading[1] !== id || !status) {
    throw new Error(
      `${decisionRoot}/${path} needs an "# ADR-NNNN: Title" heading matching its file and a Status`,
    )
  }

  return { id, path, title: heading[2]!.trim(), status, changes: header(text, "Changes") }
}

/** Owner documents named in a Changes header that do not exist. */
const missingChanges = async (record: DecisionRecord) => {
  const paths = [...(record.changes ?? "").matchAll(/`([^`]+)`/g)].map((match) => match[1]!)
  const missing: string[] = []

  for (const path of paths) {
    const found = await stat(path).then(
      () => true,
      (cause: NodeJS.ErrnoException) => {
        if (cause.code === "ENOENT") return false
        throw cause
      },
    )

    if (!found) missing.push(path)
  }

  return missing
}

export const decisionFailures = async (records: readonly DecisionRecord[]) => {
  const failures: string[] = []

  for (const record of records) {
    if (Number(record.id) < firstWithChanges) continue
    const where = `${decisionRoot}/${record.path}`

    if (record.changes === undefined) {
      failures.push(`${where} has no Changes header`)
      continue
    }

    for (const path of await missingChanges(record)) {
      failures.push(`${where} names ${path} in Changes, which does not exist`)
    }
  }

  return failures
}

export const discoverDecisions = async (): Promise<readonly DecisionRecord[]> => {
  const records: DecisionRecord[] = []

  for (const folder of ["", "archive/"]) {
    for (const name of await readdir(`${decisionRoot}/${folder}`)) {
      if (!/^\d{4}-.+\.md$/.test(name) || name.startsWith("0000-")) continue
      const path = `${folder}${name}`
      records.push(parseDecision(path, await readFile(`${decisionRoot}/${path}`, "utf8")))
    }
  }

  return records.toSorted((left, right) => left.id.localeCompare(right.id))
}

const cell = (text: string) => text.replaceAll("|", "\\|")

/** Replaces the index block of the README with one row per ADR. */
export const renderDecisionIndex = (readme: string, records: readonly DecisionRecord[]) => {
  const from = readme.indexOf(start)
  const to = readme.indexOf(end)

  if (from < 0 || to < from) throw new Error(`${decisionIndexTarget} lacks the ADR index markers`)

  const rows = [
    "| ADR | Decision | Status |",
    "| --- | --- | --- |",
    ...records.map(
      ({ id, path, title, status }) => `| [\`${id}\`](./${path}) | ${cell(title)} | ${status} |`,
    ),
  ]

  return `${readme.slice(0, from)}${start}\n\n${rows.join("\n")}\n\n${readme.slice(to)}`
}
