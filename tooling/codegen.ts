// Generates the module composition from module manifests (ADR-0094), the way TanStack Router's
// generator writes routeTree.gen.ts: whole files rebuilt from conventions, never hand-edited.
import { execFileSync } from "node:child_process"
import { readdir, readFile, stat, writeFile } from "node:fs/promises"
import { createRequire } from "node:module"
import { resolve } from "node:path"
import { pathToFileURL } from "node:url"

import * as Predicate from "effect/Predicate"
import { createJiti } from "jiti"

import type { ModuleManifest } from "../framework/modules/module/mod.ts"

const moduleRoot = "erp/modules"
export const backendTarget = "erp/runtime/modules.gen.ts"
export const webTarget = "apps/web/src/app/routes.gen.ts"
const webModules = "apps/web/src/app/modules"

export type DiscoveredModule = {
  readonly directory: string
  readonly type: string
  readonly manifest: ModuleManifest
}

const exists = async (path: string) =>
  stat(path).then(
    () => true,
    (cause: NodeJS.ErrnoException) => {
      if (cause.code === "ENOENT") return false
      throw cause
    },
  )

const isManifest = (value: unknown): value is ModuleManifest =>
  Predicate.hasProperty(value, "name") &&
  Predicate.isString(value.name) &&
  Predicate.hasProperty(value, "pages") &&
  Array.isArray(value.pages)

/** Loads each module's manifest.ts with jiti, so codegen reads the same values the runtime uses. */
export const discoverModules = async (): Promise<readonly DiscoveredModule[]> => {
  const jiti = createJiti(pathToFileURL(resolve("tooling/codegen.ts")).href, { moduleCache: false })
  const modules: DiscoveredModule[] = []
  const entries = await readdir(moduleRoot, { withFileTypes: true })
  for (const entry of entries.toSorted((a, b) => a.name.localeCompare(b.name))) {
    const path = `${moduleRoot}/${entry.name}/manifest.ts`
    if (!entry.isDirectory() || !(await exists(path))) continue
    const exports = await jiti.import<object>(resolve(path))
    const found = Object.entries(exports).flatMap(([key, value]) =>
      key.endsWith("Module") && isManifest(value) ? [[key, value] as const] : [],
    )
    if (found.length !== 1) throw new Error(`${path} must export exactly one <Name>Module manifest`)
    const [key, manifest] = found[0]!
    modules.push({ directory: entry.name, type: key.slice(0, -"Module".length), manifest })
  }
  return modules
}

export const renderBackend = (modules: readonly DiscoveredModule[]) => {
  const routed = modules.filter(({ manifest }) => manifest.http.length > 0)
  return [
    "// Generated by `pnpm run ritsei gen` from erp/modules/*/manifest.ts. Do not edit.",
    'import type { ModuleManifest } from "../../framework/modules/module/mod.ts"',
    ...modules.flatMap(({ directory, type, manifest }) => [
      ...(manifest.http.length > 0
        ? [
            `import { ${type}HttpGroup, ${type}HttpHandlers } from "../modules/${directory}/http.ts"`,
          ]
        : []),
      `import { ${type}Module } from "../modules/${directory}/mod.ts"`,
    ]),
    "",
    "/** The installed ERP modules. */",
    "export const ErpModules: ReadonlyArray<ModuleManifest> = [",
    ...modules.map(({ type }) => `  ${type}Module,`),
    "]",
    "",
    "/** HttpApi groups the runtime composes into RitseiApi. */",
    "export const ErpHttpGroups = [",
    ...routed.map(({ type }) => `  ${type}HttpGroup,`),
    "] as const",
    "",
    "/** Handler layers for ErpHttpGroups. */",
    "export const ErpHttpHandlers = [",
    ...routed.map(({ type }) => `  ${type}HttpHandlers,`),
    "] as const",
    "",
  ].join("\n")
}

export const renderWeb = (modules: readonly DiscoveredModule[]) => {
  const paged = modules.filter(({ manifest }) => manifest.pages.length > 0)
  return [
    "// Generated by `pnpm run ritsei gen` from erp/modules/*/manifest.ts pages. Do not edit.",
    'import { lazy } from "solid-js"',
    "",
    'import type { ModuleWorkspace } from "./workspace.ts"',
    ...paged.map(
      ({ directory }) =>
        `import { workspace as ${camel(directory)}Workspace } from "./modules/${directory}.workspace.ts"`,
    ),
    "",
    ...paged.map(
      ({ directory, type }) =>
        `const ${type}Page = lazy(() => import("./modules/${directory}.tsx"))`,
    ),
    "",
    "/** Routes for every installed module page. */",
    "export const moduleRoutes = [",
    ...paged.flatMap(({ type, manifest }) =>
      manifest.pages.map((page) => `  { path: ${JSON.stringify(page)}, component: ${type}Page },`),
    ),
    "]",
    "",
    "/** Home-directory and shell-navigation entries, one per module workspace, in declared order. */",
    "export const moduleWorkspaces: ReadonlyArray<ModuleWorkspace & { readonly href: string }> = [",
    ...paged.map(
      ({ directory, manifest }) =>
        `  { href: ${JSON.stringify(manifest.pages[0])}, ...${camel(directory)}Workspace },`,
    ),
    "].toSorted((left, right) => left.order - right.order)",
    "",
  ].join("\n")
}

const camel = (directory: string) =>
  directory.replace(/_([a-z0-9])/g, (_, next: string) => next.toUpperCase())

const oxfmt = (() => {
  const require = createRequire(import.meta.url)
  const packagePath = require.resolve("oxfmt/package.json")
  // SAFETY: oxfmt's package.json declares a bin map of command names to paths.
  const { bin } = require(packagePath) as { bin: Record<string, string> }
  return resolve(packagePath, "..", bin.oxfmt!)
})()

/** Formats generated source exactly as `pnpm run fmt` would, so --check compares like for like. */
export const format = (path: string, source: string) =>
  execFileSync(process.execPath, [oxfmt, `--stdin-filepath=${path}`], {
    input: source,
    encoding: "utf8",
  })

/** Missing page components or workspace metadata for a module that declares pages. */
const missingWebFiles = async (modules: readonly DiscoveredModule[]) => {
  const missing: string[] = []
  for (const { directory, manifest } of modules) {
    if (manifest.pages.length === 0) continue
    for (const file of [`${directory}.tsx`, `${directory}.workspace.ts`]) {
      if (!(await exists(`${webModules}/${file}`))) missing.push(`${webModules}/${file}`)
    }
  }
  return missing
}

/** Writes the generated files, or with `check` reports the ones that are stale. */
export const generate = async (options: { readonly check: boolean }) => {
  const modules = await discoverModules()
  const missing = await missingWebFiles(modules)
  if (missing.length > 0) throw new Error(`modules declare pages without ${missing.join(", ")}`)
  const outputs = [
    { path: backendTarget, source: format(backendTarget, renderBackend(modules)) },
    { path: webTarget, source: format(webTarget, renderWeb(modules)) },
  ]
  const stale: string[] = []
  for (const { path, source } of outputs) {
    const current = await readFile(path, "utf8").catch(() => undefined)
    if (current === source) continue
    stale.push(path)
    if (!options.check) await writeFile(path, source)
  }
  return stale
}
