import { assert, describe, it } from "@effect/vitest"
import * as Effect from "effect/Effect"

import {
  decisionFailures,
  parseDecision,
  renderDecisionIndex,
} from "../../tooling/decision-index.ts"

const adr = (id: string, extra = "") =>
  `# ADR-${id}: Pick One Owner\n\n- Status: Accepted (amended by ADR-0999)\n- Date: 2026-11-20\n${extra}`

describe("ADR index", () => {
  it("reads the title, the first word of the status, and a wrapped Changes header", () => {
    const record = parseDecision(
      "archive/0124-pick-one-owner.md",
      adr("0124", "- Changes: `AGENTS.md`,\n  `docs/README.md`\n"),
    )

    assert.deepStrictEqual(record, {
      id: "0124",
      path: "archive/0124-pick-one-owner.md",
      title: "Pick One Owner",
      status: "Accepted",
      changes: "`AGENTS.md`, `docs/README.md`",
    })
  })

  it("rejects a heading that does not match the file number", () => {
    assert.throws(() => parseDecision("0124-pick-one-owner.md", adr("0125")), /heading matching/)
  })

  it("replaces only the marked block and escapes pipes in titles", () => {
    const readme = [
      "intro",
      "<!-- adr-index:start (generated by `pnpm run ritsei gen`; do not edit) -->",
      "stale",
      "<!-- adr-index:end -->",
      "outro",
    ].join("\n")

    const rendered = renderDecisionIndex(readme, [
      { id: "0001", path: "0001-a.md", title: "A | B", status: "Accepted", changes: undefined },
    ])

    assert.include(rendered, "| [`0001`](./0001-a.md) | A \\| B | Accepted |")
    assert.notInclude(rendered, "stale")
    assert.isTrue(rendered.startsWith("intro\n") && rendered.endsWith("outro"))
  })

  it.effect("requires Changes from ADR-0123 on and checks that named documents exist", () =>
    Effect.gen(function* () {
      const failures = yield* Effect.promise(() =>
        decisionFailures([
          { id: "0122", path: "0122-a.md", title: "A", status: "Accepted", changes: undefined },
          { id: "0124", path: "0124-b.md", title: "B", status: "Proposed", changes: undefined },
          {
            id: "0125",
            path: "0125-c.md",
            title: "C",
            status: "Proposed",
            changes: "`AGENTS.md`, `docs/missing.md`",
          },
        ]),
      )

      assert.deepStrictEqual(failures, [
        "docs/decisions/0124-b.md has no Changes header",
        "docs/decisions/0125-c.md names docs/missing.md in Changes, which does not exist",
      ])
    }),
  )
})
